/* ---------- 渲染：把像素矩阵转成 SVG ---------- */
function renderPetSprite(level) {
  const lv = Math.max(1, Math.min(10, level | 0));
  const meta = PET_META[lv];
  const matrix = PET_SPRITES[lv];
  if (!meta || !matrix) return '';

  const cols = 16, rows = 16, px = 16; // 每个"像素"画 16×16 的 SVG 单位
  const size = cols * px; // 256

  // 拼接所有 <rect>，相同颜色用 <g> 分组以减小体积
  const groups = {}; // color -> [{x,y}...]
  for (let y = 0; y < rows; y++) {
    const row = matrix[y] || '';
    for (let x = 0; x < cols; x++) {
      const ch = row[x] || '.';
      if (ch === '.' || ch === ' ') continue;
      const idx = (parseInt(ch, 10) - 1);
      const color = meta.palette[idx] || meta.palette[0];
      (groups[color] = groups[color] || []).push({ x: x * px, y: y * px });
    }
  }

  let rects = '';
  for (const color in groups) {
    rects += `<g fill="${color}">`;
    for (const p of groups[color]) {
      rects += `<rect x="${p.x}" y="${p.y}" width="${px}" height="${px}"/>`;
    }
    rects += `</g>`;
  }

  return `<svg viewBox="0 0 ${size} ${size}" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">${rects}</svg>`;
}

/* ---------- 主题宠物图片（可选覆盖像素精灵）---------- */
var _themeImages = null;   // { "1": ["url1"], "2": ["url2"], ... }
var _themeLevelNames = null; // { "1": "name1", "2": "name2", ... }

/* ---------- 暴露 API ---------- */
window.PetSprites = {
  LEVEL_THRESHOLDS,
  PET_META,

  /**
   * 设置主题宠物图片映射
   * @param {object} images - { "1": ["/uploads/...png"], "2": [...], ... }
   */
  setPetImages: function (images) {
    _themeImages = images || null;
  },

  /**
   * 设置主题等级名称映射
   * @param {object} names - { "1": "初生火花", "2": "探索火花", ... }
   */
  setLevelNames: function (names) {
    _themeLevelNames = names || null;
  },

  /**
   * 获取某等级的主题图片 URL（取第一张），没有则返回 null
   */
  getImageUrl: function (level) {
    if (!_themeImages) return null;
    var urls = _themeImages[String(level)];
    return (urls && urls.length > 0) ? urls[0] : null;
  },

  /**
   * 渲染某等级的宠物图片/精灵
   * 优先使用主题图片，没有则用像素精灵
   * @param {number} level - 1~10
   * @param {object} opts  - { size?: number, cls?: string }
   */
  render: function (level, opts) {
    opts = opts || {};
    var imgUrl = this.getImageUrl(level);
    var lv = Math.max(1, Math.min(10, level | 0));

    if (imgUrl) {
      // 真实图片模式：用 <img> 标签，带 object-fit: contain 自适应
      var size = opts.size || 256;
      var cls  = opts.cls || '';
      // 用 inline style 填满容器，外部 CSS 确保图片等比例缩放
      return '<img src="' + Utils.esc(imgUrl) + '" alt="LV.' + lv + '" ' +
             'class="pet-theme-img ' + cls + '" ' +
             'style="width:' + size + 'px;height:' + size + 'px;object-fit:contain" ' +
             'draggable="false" />';
    }
    // 回退到像素精灵
    return renderPetSprite(level);
  },

  /** 取某等级的小图标（用于学生列表） */
  icon: function (level) {
    var imgUrl = this.getImageUrl(level);
    if (imgUrl) {
      return '<img src="' + Utils.esc(imgUrl) + '" alt="LV." ' +
             'class="pet-icon-img" draggable="false" />';
    }
    return renderPetSprite(level);
  },

  /** 取某等级名称 */
  name: function (level) {
    if (_themeLevelNames) {
      var n = _themeLevelNames[String(level)];
      if (n) return n;
    }
    return PET_META[level]?.name || '未知';
  },

  /** 根据分数计算当前等级 */
  levelFromScore: function (score) {
    var lv = 1;
    for (var i = 1; i <= 10; i++) {
      if (score >= LEVEL_THRESHOLDS[i]) lv = i;
    }
    return lv;
  },

  /** 取下一级所需分数（满级返回 null） */
  nextThreshold: function (level) {
    return level >= 10 ? null : LEVEL_THRESHOLDS[level + 1];
  },
};
